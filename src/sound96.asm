SndDriver	;Sound driver entry (SoundCmd). d0 = command 0-$12 through SndJumpTable; carry set and d0 = 1 for a bad
	;command
	dc.w	$0C40,$0013	;cmpi.w #$13,d0 (the build turns cmpi.w #,d0 into cmp.w)
	bcc.s	.0
	move.l	a6,-(sp)
	lea	SndJumpTable(pc),a6
	andi.l	#$FFFF,d0
	lsl.l	#2,d0
	adda.l	d0,a6
	jsr	(a6)
	movea.l	(sp)+,a6
	rts
.0
	move.w	#1,d0
	ori	#1,ccr
	rts

